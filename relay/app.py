"""Muse Relay — lightweight task queue between the Mac Canvas (via the bridge)
and the VM worker. No Chromium, no muse2api, no Muse cookies here.

Storage is the container's ephemeral disk (RELAY_DATA_DIR). Task records are
JSON files; media are files under each task's directory. The VM worker is the
durable store of last resort: it keeps results until the client acks, and
re-offers them through POST /worker/sync after a relay restart (see README).
"""

import asyncio
import json
import os
import re
import secrets
import shutil
import time
import uuid
from pathlib import Path

from fastapi import Depends, FastAPI, File, Form, Header, HTTPException, Request, UploadFile
from fastapi.responses import FileResponse, JSONResponse

# ---------------------------------------------------------------- config

DATA_DIR = Path(os.environ.get("RELAY_DATA_DIR", "/app/data"))
TASKS_DIR = DATA_DIR / "tasks"
CANVAS_KEY = os.environ.get("RELAY_CANVAS_KEY", "")
WORKER_KEY = os.environ.get("RELAY_WORKER_KEY", "")
TASK_TTL_HOURS = float(os.environ.get("RELAY_TASK_TTL_HOURS", "24"))
MAX_MEDIA_MB = int(os.environ.get("RELAY_MAX_MEDIA_MB", "2048"))

KINDS = {"chat", "image", "image_edit", "video", "responses"}
KIND_TIMEOUTS = {"chat": 300, "responses": 300, "image": 240,
                 "image_edit": 240, "video": 600}
HEARTBEAT_STALE_SECONDS = 90
MAX_JSON_BODY_BYTES = 1 * 1024 * 1024
MAX_MULTIPART_BYTES = 50 * 1024 * 1024

if not CANVAS_KEY or not WORKER_KEY:
    raise RuntimeError(
        "RELAY_CANVAS_KEY and RELAY_WORKER_KEY must both be set "
        "(on Render they are generated by the Blueprint).")

app = FastAPI(title="muse-relay")
_lock = asyncio.Lock()
_tasks: dict[str, dict] = {}          # task_id -> record (also on disk)
_by_idempotency: dict[str, str] = {}  # idempotency_key -> task_id

_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")


# ---------------------------------------------------------------- helpers

def _now() -> int:
    return int(time.time())


def _task_dir(task_id: str) -> Path:
    return TASKS_DIR / task_id


def _record_path(task_id: str) -> Path:
    return _task_dir(task_id) / "task.json"


def _safe_name(name: str) -> str:
    if not _NAME_RE.match(name) or ".." in name:
        raise HTTPException(400, "invalid file name")
    return name


def _save(rec: dict) -> None:
    d = _task_dir(rec["task_id"])
    d.mkdir(parents=True, exist_ok=True)
    tmp = d / "task.json.tmp"
    tmp.write_text(json.dumps(rec), encoding="utf-8")
    tmp.replace(_record_path(rec["task_id"]))
    rec["updated_at"] = _now()


def _public(rec: dict) -> dict:
    return {
        "task_id": rec["task_id"],
        "kind": rec["kind"],
        "status": rec["status"],
        "progress": rec["progress"],
        "error": rec["error"],
        "result": rec["result"],
        "result_media": rec["result_media"],
        "created_at": rec["created_at"],
        "updated_at": rec["updated_at"],
    }


def _load_all() -> None:
    """Rebuild the in-memory index from disk (relay restart recovery)."""
    TASKS_DIR.mkdir(parents=True, exist_ok=True)
    for path in sorted(TASKS_DIR.glob("*/task.json")):
        try:
            rec = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        if rec.get("status") == "processing":
            # The worker that held it is gone; make it claimable again.
            rec["status"] = "queued"
            rec["claimed_by"] = None
            rec["heartbeat_at"] = None
            _save(rec)
        _tasks[rec["task_id"]] = rec
        if rec.get("idempotency_key"):
            _by_idempotency[rec["idempotency_key"]] = rec["task_id"]


def _media_total_bytes() -> int:
    total = 0
    for f in TASKS_DIR.glob("*/outputs/*"):
        try:
            total += f.stat().st_size
        except OSError:
            pass
    return total


def _enforce_media_cap() -> None:
    """Drop the oldest completed tasks' media while over the cap."""
    cap = MAX_MEDIA_MB * 1024 * 1024
    if _media_total_bytes() <= cap:
        return
    done = sorted((r for r in _tasks.values() if r["status"] == "completed"),
                  key=lambda r: r["updated_at"])
    for rec in done:
        if _media_total_bytes() <= cap:
            break
        out = _task_dir(rec["task_id"]) / "outputs"
        shutil.rmtree(out, ignore_errors=True)
        rec["result_media"] = []
        if isinstance(rec.get("result"), dict):
            rec["result"] = {**rec["result"],
                             "url": None,
                             "error": "result media evicted (relay storage cap)"}
        _save(rec)


# ---------------------------------------------------------------- auth

def _bearer(authorization: str | None) -> str:
    if not authorization or not authorization.startswith("Bearer "):
        raise HTTPException(401, "missing bearer token")
    return authorization[7:]


async def canvas_auth(authorization: str | None = Header(default=None)):
    if _bearer(authorization) != CANVAS_KEY:
        raise HTTPException(401, "invalid canvas key")


async def worker_auth(authorization: str | None = Header(default=None),
                      x_worker_id: str | None = Header(default=None)):
    if _bearer(authorization) != WORKER_KEY:
        raise HTTPException(401, "invalid worker key")
    if not x_worker_id:
        raise HTTPException(400, "missing X-Worker-Id header")
    return x_worker_id


# ---------------------------------------------------------------- lifecycle

@app.on_event("startup")
async def startup():
    _load_all()
    asyncio.create_task(_janitor())


async def _janitor():
    while True:
        await asyncio.sleep(60)
        try:
            async with _lock:
                now = _now()
                # Stale claims -> re-queue.
                for rec in list(_tasks.values()):
                    if rec["status"] != "processing":
                        continue
                    hb = rec.get("heartbeat_at") or 0
                    if now - hb > HEARTBEAT_STALE_SECONDS:
                        rec["status"] = "queued"
                        rec["claimed_by"] = None
                        rec["heartbeat_at"] = None
                        _save(rec)
                    elif now - rec["created_at"] > rec["timeout_seconds"]:
                        rec["status"] = "timeout"
                        rec["error"] = "task timed out"
                        _save(rec)
                # TTL cleanup of completed/failed tasks.
                ttl = int(TASK_TTL_HOURS * 3600)
                for tid, rec in list(_tasks.items()):
                    if rec["status"] in ("completed", "failed", "timeout") \
                            and now - rec["updated_at"] > ttl:
                        shutil.rmtree(_task_dir(tid), ignore_errors=True)
                        _tasks.pop(tid, None)
                        if rec.get("idempotency_key"):
                            _by_idempotency.pop(rec["idempotency_key"], None)
                _enforce_media_cap()
        except Exception:
            pass


# ---------------------------------------------------------------- public

@app.get("/healthz")
def healthz():
    return {"status": "ok", "time": _now()}


@app.get("/v1/media/{name}")
def get_media(name: str):
    name = _safe_name(name)
    for task_dir in TASKS_DIR.iterdir():
        if not task_dir.is_dir():
            continue
        p = task_dir / "outputs" / name
        if p.is_file():
            return FileResponse(p)
    raise HTTPException(404, "media not found")


# ---------------------------------------------------------------- client API

@app.post("/v1/tasks", status_code=202)
async def create_task(request: Request, _=Depends(canvas_auth)):
    content_type = request.headers.get("content-type", "")
    if "multipart/form-data" in content_type:
        form = await request.form()
        raw = form.get("request")
        if raw is None:
            raise HTTPException(400, "missing request field")
        try:
            body = json.loads(raw)
        except Exception:
            raise HTTPException(400, "request field is not valid JSON")
        files = [v for v in form.values()
                 if hasattr(v, "filename") and v.filename]
        if len(files) > 15:
            raise HTTPException(400, "too many input files")
    else:
        raw = await request.body()
        if len(raw) > MAX_JSON_BODY_BYTES:
            raise HTTPException(413, "request body too large")
        try:
            body = json.loads(raw)
        except Exception:
            raise HTTPException(400, "body is not valid JSON")
        files = []

    kind = body.get("kind")
    if kind not in KINDS:
        raise HTTPException(400, f"unknown kind: {kind!r}")
    idem = body.get("idempotency_key") or ""
    if not isinstance(idem, str) or not idem:
        raise HTTPException(400, "idempotency_key is required")
    if kind == "image_edit" and not files:
        raise HTTPException(400, "image_edit needs input image files")

    async with _lock:
        existing = _by_idempotency.get(idem)
        if existing and existing in _tasks:
            rec = _tasks[existing]
            return JSONResponse({"task_id": rec["task_id"],
                                 "status": rec["status"],
                                 "created_at": rec["created_at"],
                                 "duplicate": True}, status_code=202)
        task_id = "task_" + secrets.token_hex(12)
        rec = {
            "task_id": task_id,
            "kind": kind,
            "model": str(body.get("model") or ""),
            "input": body.get("input") or {},
            "idempotency_key": idem,
            "status": "queued",
            "progress": 0,
            "error": None,
            "result": None,
            "result_media": [],
            "input_files": [],
            "created_at": _now(),
            "updated_at": _now(),
            "claimed_by": None,
            "heartbeat_at": None,
            "timeout_seconds": int(body.get("timeout_seconds")
                                   or KIND_TIMEOUTS[kind]),
            "result_missing": False,
        }
        _tasks[task_id] = rec
        _by_idempotency[idem] = task_id
        _save(rec)

    if files:
        in_dir = _task_dir(task_id) / "inputs"
        in_dir.mkdir(parents=True, exist_ok=True)
        names = []
        for f in files:
            name = _safe_name(f.filename)
            dest = in_dir / name
            with dest.open("wb") as out:
                while True:
                    chunk = await f.read(1024 * 1024)
                    if not chunk:
                        break
                    out.write(chunk)
            names.append(name)
        async with _lock:
            rec["input_files"] = names
            _save(rec)

    return JSONResponse({"task_id": task_id, "status": "queued",
                         "created_at": rec["created_at"]}, status_code=202)


@app.get("/v1/tasks/{task_id}")
async def get_task(task_id: str, _=Depends(canvas_auth)):
    rec = _tasks.get(task_id)
    if rec is None:
        raise HTTPException(404, "unknown task")
    return _public(rec)


@app.post("/v1/tasks/{task_id}/ack")
async def ack_task(task_id: str, _=Depends(canvas_auth)):
    async with _lock:
        rec = _tasks.get(task_id)
        if rec is None:
            raise HTTPException(404, "unknown task")
        shutil.rmtree(_task_dir(task_id), ignore_errors=True)
        _tasks.pop(task_id, None)
        if rec.get("idempotency_key"):
            _by_idempotency.pop(rec["idempotency_key"], None)
    return {"acked": task_id}


# ---------------------------------------------------------------- worker API

@app.get("/worker/tasks/next")
async def next_task(wait: int = 25, worker_id: str = Depends(worker_auth)):
    wait = max(0, min(int(wait), 60))
    deadline = time.monotonic() + wait
    while True:
        async with _lock:
            for rec in sorted(_tasks.values(), key=lambda r: r["created_at"]):
                if rec["status"] != "queued":
                    continue
                rec["status"] = "processing"
                rec["claimed_by"] = worker_id
                rec["heartbeat_at"] = _now()
                rec["progress"] = 5
                _save(rec)
                return {
                    "task_id": rec["task_id"],
                    "kind": rec["kind"],
                    "model": rec["model"],
                    "input": rec["input"],
                    "input_files": rec["input_files"],
                    "idempotency_key": rec["idempotency_key"],
                    "timeout_seconds": rec["timeout_seconds"],
                }
        if time.monotonic() >= deadline:
            return JSONResponse(status_code=204, content=None)
        await asyncio.sleep(1)


@app.get("/worker/tasks/{task_id}/inputs/{name}")
async def get_input(task_id: str, name: str, worker_id: str = Depends(worker_auth)):
    rec = _tasks.get(task_id)
    if rec is None:
        raise HTTPException(404, "unknown task")
    if rec.get("claimed_by") != worker_id:
        raise HTTPException(409, "task not claimed by this worker")
    name = _safe_name(name)
    p = _task_dir(task_id) / "inputs" / name
    if not p.is_file():
        raise HTTPException(404, "input not found")
    return FileResponse(p)


def _owned(task_id: str, worker_id: str) -> dict:
    rec = _tasks.get(task_id)
    if rec is None:
        raise HTTPException(404, "unknown task")
    if rec.get("claimed_by") != worker_id:
        raise HTTPException(409, "task not claimed by this worker")
    if rec["status"] != "processing":
        raise HTTPException(409, f"task is {rec['status']}, not processing")
    return rec


@app.post("/worker/tasks/{task_id}/heartbeat")
async def heartbeat(task_id: str, request: Request,
                    worker_id: str = Depends(worker_auth)):
    body = await request.json()
    async with _lock:
        rec = _owned(task_id, worker_id)
        rec["heartbeat_at"] = _now()
        if isinstance(body.get("progress"), int):
            rec["progress"] = max(0, min(100, body["progress"]))
        _save(rec)
    return {"ok": True}


@app.post("/worker/tasks/{task_id}/status")
async def set_status(task_id: str, request: Request,
                     worker_id: str = Depends(worker_auth)):
    body = await request.json()
    async with _lock:
        rec = _owned(task_id, worker_id)
        rec["heartbeat_at"] = _now()
        if isinstance(body.get("progress"), int):
            rec["progress"] = max(0, min(100, body["progress"]))
        if body.get("error"):
            rec["error"] = str(body["error"])[:500]
        _save(rec)
    return {"ok": True}


@app.post("/worker/tasks/{task_id}/failed")
async def mark_failed(task_id: str, request: Request,
                      worker_id: str = Depends(worker_auth)):
    body = await request.json()
    async with _lock:
        rec = _owned(task_id, worker_id)
        rec["status"] = "failed"
        rec["error"] = str(body.get("error") or "worker failed")[:500]
        _save(rec)
    return {"ok": True}


@app.post("/worker/tasks/{task_id}/result")
async def upload_result(task_id: str, request: Request,
                        worker_id: str = Depends(worker_auth)):
    content_type = request.headers.get("content-type", "")
    if "multipart/form-data" not in content_type:
        raise HTTPException(400, "result must be multipart/form-data")
    form = await request.form()
    raw = form.get("result")
    if raw is None:
        raise HTTPException(400, "missing result field")
    try:
        result = json.loads(raw)
    except Exception:
        raise HTTPException(400, "result field is not valid JSON")
    files = [v for v in form.values()
             if hasattr(v, "filename") and v.filename]

    async with _lock:
        rec = _tasks.get(task_id)
        if rec is None:
            raise HTTPException(404, "unknown task")
        # Accept from the claiming worker, or a re-upload after a relay
        # restart for a task the worker re-offered via /worker/sync.
        if rec["status"] == "processing":
            if rec.get("claimed_by") != worker_id:
                raise HTTPException(409, "task not claimed by this worker")
        elif rec["status"] == "completed" and rec.get("result_missing"):
            pass
        else:
            raise HTTPException(409, f"task is {rec['status']}")

    out_dir = _task_dir(task_id) / "outputs"
    out_dir.mkdir(parents=True, exist_ok=True)
    names = []
    for f in files:
        name = _safe_name(f.filename)
        dest = out_dir / name
        with dest.open("wb") as out:
            while True:
                chunk = await f.read(1024 * 1024)
                if not chunk:
                    break
                out.write(chunk)
        names.append(name)

    async with _lock:
        rec["result"] = result
        rec["result_media"] = names
        rec["status"] = "completed"
        rec["progress"] = 100
        rec["result_missing"] = False
        _save(rec)
        _enforce_media_cap()
    return {"ok": True, "task_id": task_id, "files": names}


@app.post("/worker/sync")
async def worker_sync(request: Request, worker_id: str = Depends(worker_auth)):
    body = await request.json()
    in_flight = body.get("in_flight") or []
    completed = body.get("completed_unacked") or []
    reply: dict = {"reattached": [], "needs_upload": [], "already_have": []}
    async with _lock:
        for tid in in_flight:
            rec = _tasks.get(tid)
            if rec is None:
                # Relay đã mất task này. Worker đang chạy dở nó, nên
                # tạo lại bản ghi processing gán cho chính worker này
                # (không đưa về queued — worker sẽ báo kết quả khi xong).
                rec = {
                    "task_id": tid, "kind": "unknown", "model": "",
                    "input": {}, "idempotency_key": "",
                    "status": "processing", "progress": 0, "error": None,
                    "result": None, "result_media": [], "input_files": [],
                    "created_at": _now(), "updated_at": _now(),
                    "claimed_by": worker_id, "heartbeat_at": _now(),
                    "timeout_seconds": 600, "result_missing": False,
                }
                _tasks[tid] = rec
                _save(rec)
                reply["reattached"].append(tid)
            elif rec["status"] == "processing" and rec.get("claimed_by") == worker_id:
                rec["heartbeat_at"] = _now()
                _save(rec)
        for item in completed:
            tid = item.get("task_id")
            if not tid:
                continue
            rec = _tasks.get(tid)
            if rec is None:
                rec = {
                    "task_id": tid, "kind": item.get("kind", "unknown"),
                    "model": item.get("model", ""), "input": {},
                    "idempotency_key": item.get("idempotency_key", ""),
                    "status": "completed", "progress": 100, "error": None,
                    "result": item.get("result"),
                    "result_media": [], "input_files": [],
                    "created_at": _now(), "updated_at": _now(),
                    "claimed_by": None, "heartbeat_at": None,
                    "timeout_seconds": 600, "result_missing": True,
                }
                _tasks[tid] = rec
                if rec["idempotency_key"]:
                    _by_idempotency[rec["idempotency_key"]] = tid
                _save(rec)
                reply["needs_upload"].append(tid)
            elif rec["status"] == "completed":
                reply["already_have"].append(tid)
            else:
                reply["needs_upload"].append(tid)
    return reply
